// node tools/cast.mjs: writes src/stage/cast.js, the stage's characters, from the Aseprite files in src/stage/cast/.
// Each file is one character: its feet at the bottom center of the canvas (local (0, 0) on the floor under them), a tag
// per pose (several frames when the pose breathes), its visible layers stacked bottom to top, and a hidden `tip` layer
// marking with one pixel where the caster's glow sits and shots leave from. Run it after editing the art.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { decodeAseprite } from './aseprite.mjs';
import { ROOT } from './lib.mjs';

const DIR = join(ROOT, 'src', 'stage', 'cast'), OUT = join(ROOT, 'src', 'stage', 'cast.js');
// a row's characters: palette indices. Never '.' (empty), quotes or a backslash: rows are written as JS strings.
const KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+,-/:;<=>?@[]^_{|}~';
const hex = (b, i) => `#${[b[i], b[i + 1], b[i + 2]].map(v => v.toString(16).padStart(2, '0')).join('')}`;

/** cast.js's source from { name: .aseprite bytes }: one palette for the cast, each pose's frames cropped to their pixels. */
export function castModule(files) {
  const palette = [], cast = {};
  for (const [name, buf] of Object.entries(files).sort(([a], [b]) => a.localeCompare(b))) {
    const s = decodeAseprite(buf), ax = s.w >> 1, ay = s.h; // the anchor: bottom center
    const art = s.layers.flatMap((l, i) => (l.name !== 'tip' && l.flags & 1 ? [i] : [])), tipAt = s.layers.findIndex(l => l.name === 'tip');
    const frame = f => {
      const px = new Array(s.w * s.h).fill(-1);
      for (const i of art) {
        const c = s.frames[f].cels[i];
        if (!c) continue;
        for (let y = 0; y < c.h; y++) for (let x = 0; x < c.w; x++) {
          const X = c.x + x, Y = c.y + y, o = (y * c.w + x) * 4;
          if (c.rgba[o + 3] < 128 || X < 0 || Y < 0 || X >= s.w || Y >= s.h) continue; // pixel art: solid or not there
          const h = hex(c.rgba, o);
          if (!palette.includes(h)) palette.push(h);
          px[Y * s.w + X] = palette.indexOf(h);
        }
      }
      const on = px.flatMap((v, i) => (v < 0 ? [] : [[i % s.w, Math.floor(i / s.w)]]));
      if (!on.length) throw new Error(`${name}: frame ${f + 1} is empty`);
      const x0 = Math.min(...on.map(p => p[0])), x1 = Math.max(...on.map(p => p[0])), y0 = Math.min(...on.map(p => p[1])), y1 = Math.max(...on.map(p => p[1]));
      const rows = Array.from({ length: y1 - y0 + 1 }, (_, y) => Array.from({ length: x1 - x0 + 1 }, (_, x) => {
        const v = px[(y0 + y) * s.w + x0 + x];
        return v < 0 ? '.' : KEYS[v];
      }).join(''));
      const t = tipAt >= 0 && s.frames[f].cels[tipAt], k = t ? [...Array(t.w * t.h).keys()].find(i => t.rgba[i * 4 + 3] > 127) : undefined;
      return { x: x0 - ax, y: y0 - ay, rows, ...(k !== undefined && { tip: [t.x + (k % t.w) - ax, t.y + Math.floor(k / t.w) - ay] }) };
    };
    if (!s.tags.length) throw new Error(`${name}: no tags; tag each pose`);
    cast[name] = Object.fromEntries(s.tags.map(g => [g.name, Array.from({ length: g.to - g.from + 1 }, (_, i) => frame(g.from + i))]));
  }
  if (palette.length > KEYS.length) throw new Error(`the cast uses ${palette.length} colors; rows hold ${KEYS.length}`);
  const pose = f => `{ x: ${f.x}, y: ${f.y}, ${f.tip ? `tip: [${f.tip}], ` : ''}rows: [\n${f.rows.map(r => `      '${r}',`).join('\n')}\n    ] }`;
  return [
    '// Generated by tools/cast.mjs from src/stage/cast/*.aseprite: edit the art there and run it again.',
    '// A pose is a list of frames; a frame is drawn from (x, y), local to the feet, a row character being an index into',
    '// PALETTE (. is empty), and tip is where the glow sits and shots leave from.',
    `export const PALETTE = [${palette.map(c => `'${c}'`).join(', ')}];`,
    '',
    'export const CAST = {',
    ...Object.entries(cast).flatMap(([name, poses]) => [
      `  ${name}: {`,
      ...Object.entries(poses).map(([p, frames]) => `    ${p}: [${frames.map(pose).join(', ')}],`),
      '  },',
    ]),
    '};',
    '',
  ].join('\n');
}

/** The Aseprite files cast.js is made from: { name: bytes }. */
export const castFiles = () => Object.fromEntries(readdirSync(DIR).filter(f => f.endsWith('.aseprite')).map(f => [f.slice(0, -9), readFileSync(join(DIR, f))]));

if (import.meta.url === `file://${process.argv[1].replaceAll('\\', '/').replace(/^\/?/, '/')}` || process.argv[1]?.endsWith('cast.mjs')) {
  writeFileSync(OUT, castModule(castFiles()));
  console.log(OUT);
}
